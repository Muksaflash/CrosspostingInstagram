export function detectPlatform(name: string): PlatformKey | null {
  const normalized = name.trim().toLowerCase();
  for (const [key, matchers] of Object.entries(platformMatchers)) {
    for (const regex of matchers) {
      if (regex.test(normalized)) {
        return key as PlatformKey;
      }
    }
  }
  return null;
}
